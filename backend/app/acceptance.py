"""End-to-end acceptance run.

Creates a real evaluation experiment over all seeded benchmarks with the three
deterministic local agents (3 repetitions), then a deliberately degraded agent
version to exercise regression detection and the release gate. Everything runs
through the real execution engine and independent verifiers.

Deterministic baselines are not LLM performance; the report says so explicitly.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app import models
from app.analytics import summarize_trials
from app.config import get_settings
from app.database import SessionLocal, init_db
from app.execution import run_experiment
from app.reports import build_report_data, write_reports
from app.seed import seed

ROOT = Path(__file__).resolve().parents[2]


def _agent(db, name: str, version: str):
    return db.query(models.Agent).filter_by(name=name, version=version).first()


def make_exp(db, name, agents, benches, reps, baseline_id=None, description="", policy=None):
    e = models.Experiment(
        name=name, description=description, repetitions=reps,
        agent_ids=json.dumps([a.id for a in agents]),
        benchmark_ids=json.dumps([b.id for b in benches]), seed=42,
        baseline_experiment_id=baseline_id, policy=json.dumps(policy or {}),
        created_by="acceptance-script",
    )
    db.add(e)
    db.commit()
    db.refresh(e)
    for a in agents:
        for b in benches:
            for r in range(1, reps + 1):
                db.add(models.Trial(experiment_id=e.id, agent_id=a.id, benchmark_id=b.id,
                                    repetition=r, status="queued"))
    db.commit()
    return e


def _persist_report(db, experiment, baseline, policy, label):
    agents = {a.id: {"name": a.name, "version": a.version, "kind": a.kind,
                     "provider": a.provider, "model": a.model} for a in db.query(models.Agent).all()}
    benches = {b.id: {"task_id": b.task_id, "version": b.version, "name": b.name,
                      "category": b.category, "difficulty": b.difficulty} for b in db.query(models.Benchmark).all()}
    data = build_report_data(db, models, experiment, baseline, policy)
    out = Path(get_settings().resolved(get_settings().artifact_dir)) / f"exp-{experiment.id}" / "report"
    paths = write_reports(data, out, agents, benches)
    row = models.ReleaseReport(
        experiment_id=experiment.id,
        baseline_experiment_id=baseline.id if baseline else None,
        gate_status=data["gate"], gate_reasons=json.dumps(data["gate_reasons"]),
        summary=json.dumps(data["summary"], default=str), policy=json.dumps(data["policy"]),
        markdown_path=paths["markdown"], html_path=paths["html"],
        json_path=paths["json"], pdf_path=paths["pdf"], created_by="acceptance-script",
    )
    db.add(row)
    db.commit()
    db.refresh(row)
    if label:
        example = ROOT / "reports" / "example-release-report"
        write_reports(data, example, agents, benches)
        (example / "README.md").write_text(
            "# Example release report\n\n"
            "Generated by `python -m app.acceptance` from a real local run. The candidate is a deliberately "
            "degraded configuration of the scripted agent; the gate is expected to fail on quality and safety "
            "regressions. Deterministic baselines are not LLM performance.\n"
        )
    return row, data


def main() -> int:
    init_db()
    db = SessionLocal()
    try:
        print("seed:", seed(db))
        benches = db.query(models.Benchmark).filter_by(archived=False).order_by(models.Benchmark.task_id).all()
        if len(benches) < 6:
            print(f"expected at least 6 benchmarks, found {len(benches)}", file=sys.stderr)
            return 2
        noop = _agent(db, "noop-baseline", "1.0.0")
        rule = _agent(db, "rule-based-baseline", "1.0.0")
        scripted = _agent(db, "scripted-tool-agent", "1.0.0")
        degraded = _agent(db, "scripted-tool-agent", "1.1.0-degraded")
        if not all((noop, rule, scripted, degraded)):
            print("seeded agents missing; delete the dev DB and retry", file=sys.stderr)
            return 2

        main_exp = make_exp(
            db, "Acceptance: 3 local agents x 6 tasks x 3 reps", [noop, rule, scripted], benches, 3,
            description="Deterministic local baselines. Harness evidence only, not LLM performance.",
        )
        run_experiment(db, main_exp)
        db.refresh(main_exp)
        mt = db.query(models.Trial).filter_by(experiment_id=main_exp.id).all()
        ms = summarize_trials(mt)
        print(f"MAIN experiment={main_exp.id} status={main_exp.status} overall={ms['overall']}")
        for cell in ms["cells"]:
            print(f"  cell agent={cell['agent_name']} task={cell['benchmark_task_id']} "
                  f"success={cell['successes']}/{cell['trials']} reward={cell['mean_reward']} "
                  f"failures={cell['failure_distribution']}")

        main_report, main_data = _persist_report(
            db, main_exp, None, {"min_success_rate": 0.3, "min_trials": 9,
                                 "require_no_security_violations": False}, label=False,
        )
        print(f"MAIN report={main_report.id} gate={main_data['gate']} reasons={main_data['gate_reasons']}")

        # Deliberate regression: same agent name, degraded configuration version.
        reg_exp = make_exp(
            db, "Regression demo: scripted agent 1.0.0 vs degraded 1.1.0", [degraded], benches, 3,
            baseline_id=main_exp.id,
            description="Candidate configuration intentionally falls back to naive behaviour.",
            policy={"max_success_drop": 0.1, "max_latency_ratio": 2.0, "block_on_security_regression": True},
        )
        run_experiment(db, reg_exp)
        db.refresh(reg_exp)
        reg_report, reg_data = _persist_report(
            db, reg_exp, main_exp,
            {"min_success_rate": 0.6, "min_trials": 9, "max_success_drop": 0.1,
             "block_on_security_regression": True, "require_no_security_violations": True},
            label=True,
        )
        print(f"REGRESSION experiment={reg_exp.id} report={reg_report.id} gate={reg_data['gate']}")
        print(f"  reasons={reg_data['gate_reasons']}")
        print(f"  regressions={[(r['type'], r['agent'], r['benchmark_id']) for r in reg_data['regressions']]}")

        summary = {
            "main_experiment_id": main_exp.id,
            "main_status": main_exp.status,
            "main_overall": main_data["summary"]["overall"],
            "main_gate": main_data["gate"],
            "regression_experiment_id": reg_exp.id,
            "regression_gate": reg_data["gate"],
            "regression_count": len(reg_data["regressions"]),
            "regression_types": sorted({r["type"] for r in reg_data["regressions"]}),
            "example_report": str(ROOT / "reports" / "example-release-report"),
            "disclosure": "Local deterministic baselines are not LLM performance.",
        }
        (ROOT / "reports" / "acceptance-summary.json").write_text(json.dumps(summary, indent=2, default=str))
        print("ACCEPTANCE", json.dumps(summary, indent=2, default=str))
        return 0 if reg_data["regressions"] else 1
    finally:
        db.close()


if __name__ == "__main__":
    raise SystemExit(main())
