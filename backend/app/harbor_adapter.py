"""Harbor-compatible adapter (harbor-framework task layout).

Exports a native benchmark as a Harbor task directory
(``task.toml`` + ``instruction.md`` + ``environment/`` + ``tests/test.sh``) and
imports Harbor tasks back into the native benchmark format. Harbor's verifier
contract is honoured by writing ``/logs/verifier/reward.txt`` and
``reward.json``.

The exported verifier is a copy of the real deterministic verifier — never a
placeholder that always returns success. Trajectory-only boundary evidence is
unavailable outside the native harness and is disclosed in the verifier output.
"""
from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

VERIFIER_ENTRYPOINT = '''"""Run an AgentEvalOps verifier inside a Harbor task container."""
import json
import sys
from pathlib import Path

TESTS = Path(__file__).resolve().parent
WORKSPACE = Path("/workspace")
sys.path.insert(0, str(TESTS))

from verifiers import VERIFIERS  # noqa: E402

task = json.loads((TESTS / "task.json").read_text())
verifier = VERIFIERS[task["verifier"]]
task["_dir"] = str(TESTS)


class NoTrajectory:
    manifest = task
    trajectory = []
    permission_attempts = []


result = verifier(WORKSPACE, NoTrajectory())
result["harbor_note"] = (
    "Boundary checks that require the native tool trajectory are unavailable in this export. "
    "Workspace/output checks are the same deterministic verifier used by AgentEvalOps."
)
out = Path("/logs/verifier")
out.mkdir(parents=True, exist_ok=True)(Path("/logs/verifier/reward.json")).write_text(json.dumps(result, default=str, indent=2))
(Path("/logs/verifier/reward.txt")).write_text(f"{float(result.get('reward', 0.0)):.4f}\\n")
print(json.dumps({k: result.get(k) for k in ("reward", "passed", "evidence", "failure_category")}, indent=2))
sys.exit(0 if result.get("passed") else 1)
'''

TEST_SH = '''#!/bin/bash
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export PYTHONPATH="/workspace:${SCRIPT_DIR}/verifier${PYTHONPATH:+:$PYTHONPATH}"
mkdir -p /logs/verifier
python3 "${SCRIPT_DIR}/verifier/run.py"
rc=$?
if [ ! -f /logs/verifier/reward.txt ]; then
  echo "Verifier did not produce a reward; writing 0.0" >&2
  echo "0.0" > /logs/verifier/reward.txt
fi
exit "$rc"
'''


def is_harbor_available() -> bool:
    return shutil.which("harbor") is not None


def export_harbor_task(manifest: dict, src_dir: Path, dest_root: Path) -> Path:
    dest = dest_root / manifest["task_id"]
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True, exist_ok=True)
    toml = (
        f'[metadata]\nname = "{manifest["task_id"]}"\nversion = "{manifest["version"]}"\n'
        f'difficulty = "{manifest.get("difficulty", "medium")}"\n'
        f'category = "{manifest.get("category", "general")}"\n'
        f"tags = {json.dumps(manifest.get('tags', []))}\n\n"
        f"[verifier]\ntimeout_sec = 60.0\n\n"
        f"[agent]\ntimeout_sec = {float(manifest.get('timeout_sec', 60))}\n\n"
        f"[environment]\ncpus = 1\nmemory_mb = 512\n"
    )
    (dest / "task.toml").write_text(toml)
    (dest / "instruction.md").write_text(manifest.get("instruction", ""))
    env = dest / "environment"
    env.mkdir(exist_ok=True)
    (env / "Dockerfile").write_text(
        "FROM python:3.12-slim\n"
        "RUN pip install --no-cache-dir pytest==8.3.4\n"
        "WORKDIR /workspace\nCOPY workspace/ /workspace/\n"
    )
    ws = src_dir / "workspace"
    if ws.exists():
        shutil.copytree(ws, env / "workspace", dirs_exist_ok=True)

    tests = dest / "tests"
    verifier_dir = tests / "verifier"
    verifier_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(Path(__file__).with_name("verifiers.py"), verifier_dir / "verifiers.py")
    (verifier_dir / "run.py").write_text(VERIFIER_ENTRYPOINT)
    exported = {k: v for k, v in manifest.items() if not k.startswith("_")}
    (tests / "task.json").write_text(json.dumps(exported, indent=2))
    private = src_dir / "private"
    if private.exists():
        shutil.copytree(private, tests / "private", dirs_exist_ok=True)
    (tests / "test.sh").write_text(TEST_SH)
    (tests / "test.sh").chmod(0o755)
    (dest / "README.md").write_text(
        f"# {manifest['task_id']} (Harbor export)\n\n"
        "Generated by AgentEvalOps. The verifier in `tests/verifier` is the same deterministic verifier "
        "used natively. Boundary evidence that depends on the native tool trajectory is not available in "
        "this export and is disclosed in `reward.json`.\n"
    )
    return dest


def import_harbor_task(harbor_dir: Path, dest_root: Path) -> dict:
    import tomllib

    cfg_path = harbor_dir / "task.toml"
    if not cfg_path.exists():
        raise ValueError("Not a Harbor task: task.toml missing")
    cfg = tomllib.loads(cfg_path.read_text())
    meta = cfg.get("metadata", {})
    task_id = meta.get("name") or harbor_dir.name
    dest = dest_root / task_id
    dest.mkdir(parents=True, exist_ok=True)
    instr = harbor_dir / "instruction.md"
    manifest = {
        "task_id": task_id, "version": str(meta.get("version", "1.0.0")), "name": task_id,
        "description": f"Imported Harbor task {task_id}",
        "difficulty": meta.get("difficulty", "medium"),
        "category": meta.get("category", "harbor"), "tags": meta.get("tags", []),
        "timeout_sec": int(float(cfg.get("agent", {}).get("timeout_sec", 60))),
        "verifier": "pytest", "hidden_tests": "private/test_task.py",
        "tools": ["read_file", "write_file", "list_files"],
    }
    (dest / "task.json").write_text(json.dumps(manifest, indent=2))
    (dest / "instruction.md").write_text(instr.read_text() if instr.exists() else "")
    ws = dest / "workspace"
    ws.mkdir(exist_ok=True)
    env_ws = harbor_dir / "environment" / "workspace"
    if env_ws.exists():
        shutil.copytree(env_ws, ws, dirs_exist_ok=True)
    # Convert Harbor verifier assets when they are pytest-based. Otherwise the
    # import keeps the tests for a human to map and fails loudly if selected.
    private = dest / "private"
    private.mkdir(exist_ok=True)
    test_root = harbor_dir / "tests"
    candidates = []
    if test_root.exists():
        candidates = [p for p in test_root.rglob("test*.py") if p.is_file()]
    if candidates:
        copied = []
        for candidate in candidates:
            target = private / candidate.name
            shutil.copy2(candidate, target)
            copied.append(target.name)
        manifest["hidden_tests"] = f"private/{copied[0]}"
        (dest / "task.json").write_text(json.dumps(manifest, indent=2))
    else:
        (private / "README.md").write_text(
            "Harbor test assets were not pytest files. Add a pytest file named test_task.py here and "
            "review the verifier mapping before running this benchmark.\n"
        )
    (dest / "README.md").write_text(
        f"# {task_id} (Harbor import)\n\nImported via the AgentEvalOps Harbor adapter. "
        "Review `private/` and the verifier mapping before trusting scores.\n"
    )
    return manifest


def parse_harbor_reward(trial_dir: Path) -> dict | None:
    # Harbor docs: reward.txt takes priority if both files exist.
    for rel in ("logs/verifier/reward.txt", "reward.txt"):
        p = trial_dir / rel
        if p.exists():
            try:
                return {"reward": float(p.read_text().strip()), "raw": p.read_text().strip()}
            except Exception:
                pass
    for rel in ("logs/verifier/reward.json", "reward.json"):
        p = trial_dir / rel
        if p.exists():
            try:
                data = json.loads(p.read_text())
                return {"reward": float(data.get("reward", 0)), "raw": data}
            except Exception:
                pass
    return None


def run_harbor_job(*args, timeout=120) -> dict:
    if not is_harbor_available():
        return {"available": False,
                "detail": "Harbor CLI not installed; native engine used instead. Install: pip install harbor."}
    proc = subprocess.run(["harbor", *args], capture_output=True, text=True, timeout=timeout)
    return {"available": True, "returncode": proc.returncode,
            "stdout": proc.stdout[-2000:], "stderr": proc.stderr[-2000:]}
